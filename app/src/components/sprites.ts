export function spriteFor(stage: Stage, mood: Mood): string[] {
  if (stage === 'egg' || mood === 'sleepy') return SPRITES.egg;
  const down = mood === 'sad' || mood === 'sick' || mood === 'worried';
  return SPRITES[`${stage}-${down ? 'down' : 'up'}`] ?? SPRITES['baby-up'];
}

export function pixelColor(token: string, mood: Mood): string | null {
  if (token === '.' || token === ' ') return null;
  if (mood === 'sick' && SICK[token]) return SICK[token];
  return COLORS[token] ?? '#1B2430';
}
